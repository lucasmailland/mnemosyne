#!/usr/bin/env node
/**
 * Idempotent provisioner for the mnemosyne application LOGIN role.
 * Runs as the third CMD step in docker/Dockerfile.migrate, after both
 * migration streams complete. Must be called as superuser (DATABASE_URL).
 *
 * Env:
 *   DATABASE_URL          – superuser connection (same as migrations, required)
 *   MNEMO_APP_DB_PASSWORD – password for the LOGIN role (required in production;
 *                           if unset, logs a warning and exits 0 so local dev
 *                           can skip provisioning when MNEMO_ALLOW_UNSAFE_DB_ROLE=true)
 *   MNEMO_APP_DB_USER     – role name (default: mnemo_app)
 */

const url = process.env.DATABASE_URL;
if (!url) {
  console.error("provision-app-role: DATABASE_URL is required");
  process.exit(1);
}

const password = process.env.MNEMO_APP_DB_PASSWORD;
if (!password) {
  console.warn(
    "provision-app-role: MNEMO_APP_DB_PASSWORD not set — skipping LOGIN role creation.\n" +
      "In production set MNEMO_APP_DB_PASSWORD. In local dev set MNEMO_ALLOW_UNSAFE_DB_ROLE=true\n" +
      "on the server to connect as superuser instead."
  );
  process.exit(0);
}

const user = process.env.MNEMO_APP_DB_USER ?? "mnemo_app";
const dbName = new URL(url).pathname.replace(/^\//, "") || "mnemo";

const { default: postgres } = await import("postgres");
const sql = postgres(url, { max: 1, idle_timeout: 5, connect_timeout: 10 });

try {
  // Pass sensitive values through GUC so they never appear in SQL text.
  await sql`SELECT set_config('mnemo.provision_pw',   ${password}, false)`;
  await sql`SELECT set_config('mnemo.provision_user', ${user},     false)`;
  await sql`SELECT set_config('mnemo.provision_db',   ${dbName},   false)`;

  // NOLOGIN group roles (idempotent — also created by the baseline migration).
  await sql.unsafe(`
    DO $roles$ BEGIN
      IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'mnemo_app_role') THEN
        CREATE ROLE mnemo_app_role NOLOGIN NOSUPERUSER NOBYPASSRLS;
      END IF;
      IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_user') THEN
        CREATE ROLE app_user NOLOGIN NOSUPERUSER NOBYPASSRLS;
      END IF;
      IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_org_user') THEN
        CREATE ROLE app_org_user NOLOGIN NOSUPERUSER NOBYPASSRLS;
      END IF;
    END $roles$;
  `);

  // LOGIN connection role — create or update password.
  await sql.unsafe(`
    DO $login$
    DECLARE
      v_user text := current_setting('mnemo.provision_user');
      v_pw   text := current_setting('mnemo.provision_pw');
      v_db   text := current_setting('mnemo.provision_db');
    BEGIN
      IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = v_user) THEN
        EXECUTE format(
          'CREATE ROLE %I LOGIN PASSWORD %L NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE',
          v_user, v_pw);
      ELSE
        EXECUTE format('ALTER ROLE %I PASSWORD %L', v_user, v_pw);
      END IF;
      EXECUTE format('GRANT mnemo_app_role TO %I', v_user);
      EXECUTE format('GRANT app_user       TO %I', v_user);
      EXECUTE format('GRANT app_org_user   TO %I', v_user);
      EXECUTE format('GRANT CONNECT ON DATABASE %I TO %I', v_db, v_user);
      EXECUTE format('GRANT USAGE ON SCHEMA mnemosyne TO %I', v_user);
      EXECUTE format('GRANT USAGE ON SCHEMA public    TO %I', v_user);
    END $login$;
  `);

  // Session defaults for the role, in this database. The server sends the same
  // values as startup parameters (search_path and MNEMO_PG_*_TIMEOUT_MS, see
  // @mnemo-ai/types pg-session.ts), and those win on a direct connection; a
  // pooler that drops startup parameters (pgBouncer in docker-compose.prod.yml)
  // leaves the session with these. Values are whole milliseconds; 0 = no limit.
  const ms = (name, fallback) => {
    const v = Number(process.env[name] ?? fallback);
    return Number.isInteger(v) && v >= 0 ? v : fallback;
  };
  const timeouts = {
    statement_timeout: ms("MNEMO_PG_STATEMENT_TIMEOUT_MS", 60000),
    lock_timeout: ms("MNEMO_PG_LOCK_TIMEOUT_MS", 15000),
    idle_in_transaction_session_timeout: ms("MNEMO_PG_IDLE_IN_TRANSACTION_TIMEOUT_MS", 60000),
  };
  await sql.unsafe(`
    DO $defaults$
    DECLARE
      v_user text := current_setting('mnemo.provision_user');
      v_db   text := current_setting('mnemo.provision_db');
    BEGIN
      EXECUTE format('ALTER ROLE %I IN DATABASE %I SET search_path = mnemosyne, public', v_user, v_db);
      ${Object.entries(timeouts)
        .map(
          ([k, v]) =>
            `EXECUTE format('ALTER ROLE %I IN DATABASE %I SET ${k} = ${v}', v_user, v_db);`
        )
        .join("\n      ")}
    END $defaults$;
  `);

  // Sequences needed by SERIAL / GENERATED BY DEFAULT AS IDENTITY columns.
  await sql.unsafe(`
    GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA mnemosyne TO mnemo_app_role;
    GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public    TO app_user;
  `);

  // Table-level DML privileges so the server can operate without superuser.
  // mnemo_api_keys has no RLS, so mnemo_app_role needs explicit INSERT/SELECT
  // for the bootstrap endpoint and the auth lookup path.
  await sql.unsafe(`
    GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA mnemosyne TO mnemo_app_role;
    GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public    TO app_user;

    REVOKE UPDATE, DELETE ON TABLE
      mnemosyne.mnemo_harness_loss,
      mnemosyne.mnemo_harness_retraction,
      mnemosyne.mnemo_harness_message_tombstone,
      mnemosyne.mnemo_extraction_provenance
    FROM mnemo_app_role;

    REVOKE DELETE ON TABLE
      mnemosyne.mnemo_harness_workspace_control,
      mnemosyne.mnemo_harness_ingestion_event,
      mnemosyne.mnemo_managed_collapse_operation,
      mnemosyne.mnemo_managed_collapse_effect
    FROM mnemo_app_role;
  `);

  // S3/S4 (SEC-6): the audit log and the deletion log are append-only. The
  // blanket GRANT above re-handed UPDATE/DELETE on both after every deploy,
  // leaving the immutability triggers as the only layer. Revoke them on the
  // audit log's partitions too: a partition addressed by name is checked
  // against its own ACL, and "ALL TABLES" includes every one of them.
  // Partitions keep NO privilege at all (APP-059): they carry no RLS policy,
  // so a SELECT by name would read every workspace; the app goes through the
  // parent, which only checks the parent ACL and applies its RLS.
  await sql.unsafe(`
    REVOKE UPDATE, DELETE, TRUNCATE ON TABLE
      mnemosyne.mnemo_audit_log,
      mnemosyne.mnemo_deletion_log
    FROM mnemo_app_role;

    DO $audit$
    DECLARE
      part regclass;
    BEGIN
      FOR part IN
        SELECT i.inhrelid::regclass
        FROM pg_inherits i
        WHERE i.inhparent = 'mnemosyne.mnemo_audit_log'::regclass
      LOOP
        EXECUTE format('REVOKE ALL ON TABLE %s FROM mnemo_app_role', part);
      END LOOP;
    END $audit$;
  `);

  // Accounts stage A (0050, 0052, 0054): the blanket GRANT above re-hands
  // writes on tables that only SECURITY DEFINER functions may change.
  // * mnemo_instance_admin, the superadmin list: SELECT only.
  // * mnemo_link_token, the single-use link hashes: no access at all.
  // * mnemo_user.disabled_at: a column REVOKE does nothing while the table-level
  //   UPDATE stands, so revoke that and grant UPDATE on every other column
  //   (read from the catalog, so columns added later stay writable).
  // Guarded so the script still runs against a schema that predates them.
  await sql.unsafe(`
    DO $accounts$
    DECLARE
      v_columns text;
    BEGIN
      IF to_regclass('mnemosyne.mnemo_instance_admin') IS NOT NULL THEN
        REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON TABLE mnemosyne.mnemo_instance_admin FROM mnemo_app_role;
      END IF;
      IF to_regclass('mnemosyne.mnemo_link_token') IS NOT NULL THEN
        REVOKE ALL ON TABLE mnemosyne.mnemo_link_token FROM mnemo_app_role;
      END IF;
      IF EXISTS (
        SELECT 1 FROM pg_attribute
        WHERE attrelid = 'mnemosyne.mnemo_user'::regclass AND attname = 'disabled_at' AND NOT attisdropped
      ) THEN
        SELECT string_agg(quote_ident(attname), ', ' ORDER BY attnum) INTO v_columns
        FROM pg_attribute
        WHERE attrelid = 'mnemosyne.mnemo_user'::regclass
          AND attnum > 0 AND NOT attisdropped AND attname <> 'disabled_at';
        REVOKE UPDATE ON TABLE mnemosyne.mnemo_user FROM mnemo_app_role;
        EXECUTE format('GRANT UPDATE (%s) ON TABLE mnemosyne.mnemo_user TO mnemo_app_role', v_columns);
      END IF;
    END $accounts$;
  `);

  // WP-5 (CHAOS-8): fact revision history is append-only (migration 0044).
  // The blanket GRANT above re-hands UPDATE/DELETE after every deploy; take
  // them back. Guarded so the script still runs against a schema that
  // predates the table.
  await sql.unsafe(`
    DO $revision$ BEGIN
      IF to_regclass('mnemosyne.mnemo_fact_revision') IS NOT NULL THEN
        REVOKE UPDATE, DELETE, TRUNCATE ON TABLE mnemosyne.mnemo_fact_revision FROM mnemo_app_role;
      END IF;
    END $revision$;
  `);

  console.log(
    `provision-app-role: "${user}" provisioned — ` +
      `mnemo_app_role + app_user + app_org_user, CONNECT on "${dbName}"`
  );
} finally {
  await sql.end({ timeout: 5 });
}
