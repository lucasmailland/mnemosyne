import { mnemoSchema } from "./mnemo_schema.js";
import { text, boolean, timestamp, jsonb, uuid } from "drizzle-orm/pg-core";
import { bigint } from "drizzle-orm/pg-core";
import { inet, bytea } from "./_custom-types.js";

/**
 * mnemo_audit_log — partitioned by RANGE(created_at).
 * Drizzle models the parent table only; partition child tables are managed
 * by the SQL migration and not represented here.
 */
export const auditLogTable = mnemoSchema.table("mnemo_audit_log", {
  id: bigint("id", { mode: "number" }).generatedAlwaysAsIdentity().primaryKey(),
  workspaceId: uuid("workspace_id").notNull(),
  actorType: text("actor_type").notNull(),
  actorId: text("actor_id").notNull(),
  action: text("action").notNull(),
  resource: text("resource").notNull(),
  resourceId: text("resource_id"),
  metadata: jsonb("metadata"),
  ipAddress: inet("ip_address"),
  userAgent: text("user_agent"),
  traceId: text("trace_id"),
  createdAt: timestamp("created_at", { withTimezone: true, mode: "date" }).notNull().defaultNow(),
  merkleHash: bytea("merkle_hash"),
  isTerminal: boolean("is_terminal").notNull().default(false),
  actorDekId: text("actor_dek_id"),
  // C2: app-generated UUID committed into the Merkle chain (PK is BIGINT IDENTITY,
  // unknown pre-INSERT; entry_uid is generated by the app before hashing).
  entryUid: uuid("entry_uid"),
});

export type SelectAuditLog = typeof auditLogTable.$inferSelect;
export type InsertAuditLog = typeof auditLogTable.$inferInsert;
