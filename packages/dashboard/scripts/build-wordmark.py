#!/usr/bin/env python3
"""Generates components/brand/wordmark-glyphs.ts: MNΣMOSΥNΣ outlined from GFS Didot (OFL).

The font is downloaded into a temp dir at run time (network access needed) and never committed.
Needs fontTools: pip install fonttools
Run: python3 scripts/build-wordmark.py
"""
import tempfile
import urllib.request
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

URL = "https://github.com/google/fonts/raw/main/ofl/gfsdidot/GFSDidot-Regular.ttf"
TEXT = "MNΣMOSΥNΣ"  # Σ = U+03A3, Υ = U+03A5 (Greek capitals)
TRACK = 0.14  # em, added after every glyph but the last
OUT = Path(__file__).resolve().parent.parent / "components/brand/wordmark-glyphs.ts"

with tempfile.TemporaryDirectory() as tmp:
    ttf = Path(tmp) / "GFSDidot-Regular.ttf"
    urllib.request.urlretrieve(URL, ttf)
    font = TTFont(ttf)

upm = font["head"].unitsPerEm
cmap = font.getBestCmap()
glyphs = font.getGlyphSet()
hmtx = font["hmtx"]
asc, desc = font["hhea"].ascent, font["hhea"].descent

pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
x = 0.0
for i, ch in enumerate(TEXT):
    name = cmap[ord(ch)]
    # Flip y: font y-up -> SVG y-down, baseline at y = asc.
    glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, x, asc)))
    x += hmtx[name][0] + (TRACK * upm if i < len(TEXT) - 1 else 0)

path = pen.getCommands()
viewbox = f"0 0 {round(x)} {asc - desc}"
OUT.write_text(
    "// Generated by scripts/build-wordmark.py from GFS Didot (SIL OFL). Do not edit.\n"
    f"export const WORDMARK_VIEWBOX = {viewbox!r};\n"
    f"export const WORDMARK_PATH =\n  {path!r};\n".replace("'", '"')
)
print(f"{len(TEXT)} glyphs, viewBox {viewbox}, {len(path)} path chars -> {OUT}")
