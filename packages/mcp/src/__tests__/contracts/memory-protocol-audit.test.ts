/** tools/list as served by the full registry (descriptions come from the i18n catalog). */
async function listRegisteredTools(locale?: Locale) {
  const server = new McpServer({ name: "audit-registry", version: "1.0.0" });
  registerAllTools(server, {} as unknown as MnemosyneClient, locale);
  const client = new Client({ name: "test-client", version: "1.0.0" }, { capabilities: {} });
  const [cTransport, sTransport] = InMemoryTransport.createLinkedPair();
  await Promise.all([client.connect(cTransport), server.connect(sTransport)]);
  const { tools } = await client.listTools();
  await Promise.all([client.close(), server.close()]);
  return new Map(tools.map((tool) => [tool.name, tool]));
}

function fieldDescription(
  tool: { inputSchema?: { properties?: Record<string, unknown> } } | undefined,
  field: string
): string {
  return (
    (tool?.inputSchema?.properties?.[field] as { description?: string } | undefined)?.description ??
    ""
  );
}

