describe("memory protocol audit - registerRemember subtype and decision guidance", () => {
  const FACT_SUBTYPES_13 = [
    "preference",
    "trait",
    "event",
    "relationship",
    "skill",
    "concern",
    "architecture",
    "bugfix",
    "config",
    "discovery",
    "policy",
    "process",
    "other",
  ] as const;

  it.each([
    ["en-US", /choice with rationale is a decision: use memory_decide/i],
    ["es-419", /elección con justificación es una decisión: usa memory_decide/i],
  ] as const)(
    "documents all 13 fact subtypes including other and recommends memory_decide for a choice with rationale (%s)",
    async (locale, decisionGuidance) => {
      const tools = await listRegisteredTools(locale);
      const rememberTool = tools.get("memory_remember");
      expect(rememberTool).toBeDefined();
      expect(rememberTool?.description).toBeTruthy();

      const subtypeDesc = fieldDescription(rememberTool, "subtype");
      expect(subtypeDesc).toMatch(decisionGuidance);
      for (const subtype of FACT_SUBTYPES_13) {
        expect(subtypeDesc).toContain(`'${subtype}'`);
      }
    }
  );

  it("preserves omitted, unknown, explicit other, and skill writes and server warnings with fidelity", async () => {
    const calls: Array<{ params: Record<string, unknown>; idempotencyKey?: string }> = [];
    const fakeClient = {
      remember: vi.fn(
        async (params: Record<string, unknown>, _opts?: unknown, idempotencyKey?: string) => {
          calls.push({ params, idempotencyKey });
          const warnings =
            params.subtype &&
            !FACT_SUBTYPES_13.includes(params.subtype as (typeof FACT_SUBTYPES_13)[number])
              ? [`Unknown subtype '${params.subtype}' stored as 'other'`]
              : undefined;
          return {
            id: `fact_${calls.length}`,
            statement: params.statement,
            status: "active",
            warnings,
          };
        }
      ),
    } as unknown as MnemosyneClient;

    const server = new McpServer({ name: "audit", version: "1.0.0" });
    registerRemember(server, fakeClient);
    const client = new Client({ name: "test-client", version: "1.0.0" }, { capabilities: {} });
    const [cTransport, sTransport] = InMemoryTransport.createLinkedPair();
    await Promise.all([client.connect(cTransport), server.connect(sTransport)]);

    // 1. Omitted
    const r1 = await client.callTool({
      name: "memory_remember",
      arguments: { statement: "Fact 1", sessionId: "sess-1" },
    });
    expect(r1.isError).toBeFalsy();
    expect(calls[0]!.params.statement).toBe("Fact 1");
    expect(calls[0]!.params.sessionId).toBe("sess-1");
    expect(calls[0]!.params.subtype).toBeUndefined();
    expect(JSON.parse(((r1.content as unknown[])[0] as { text: string }).text).status).toBe(
      "active"
    );

    // 2. Unknown subtype
    const r2 = await client.callTool({
      name: "memory_remember",
      arguments: { statement: "Fact 2", subtype: "custom_unk", sessionId: "sess-1" },
    });
    expect(r2.isError).toBeFalsy();
    expect(calls[1]!.params.subtype).toBe("custom_unk");
    expect(calls[1]!.params.sessionId).toBe("sess-1");
    const parsed2 = JSON.parse(((r2.content as unknown[])[0] as { text: string }).text);
    expect(parsed2.warnings).toEqual(["Unknown subtype 'custom_unk' stored as 'other'"]);
    expect(((r2.content as unknown[])[0] as { text: string }).text).toContain(
      "Unknown subtype 'custom_unk' stored as 'other'"
    );

    // 3. Explicit other
    const r3 = await client.callTool({
      name: "memory_remember",
      arguments: { statement: "Fact 3", subtype: "other", sessionId: "sess-1" },
    });
    expect(r3.isError).toBeFalsy();
    expect(calls[2]!.params.subtype).toBe("other");
    expect(calls[2]!.params.sessionId).toBe("sess-1");
    expect(JSON.parse(((r3.content as unknown[])[0] as { text: string }).text).status).toBe(
      "active"
    );

    // 4. Subtype skill
    const r4 = await client.callTool({
      name: "memory_remember",
      arguments: { statement: "Fact 4", subtype: "skill", sessionId: "sess-1" },
    });
    expect(r4.isError).toBeFalsy();
    expect(calls[3]!.params.subtype).toBe("skill");
    expect(calls[3]!.params.sessionId).toBe("sess-1");
    expect(
      JSON.parse(((r4.content as unknown[])[0] as { text: string }).text).warnings
    ).toBeUndefined();

    await Promise.all([client.close(), server.close()]);
  });
});

describe("memory protocol audit - registerDecide and registerEpisodeEnd session provenance", () => {
  it("schema has no sessionId, guidance aligns provenance, and decision preserves body/conversationId/scopeRef", async () => {
    let capturedDecision: Record<string, unknown> | undefined;
    const fakeClient = {
      createDecision: vi.fn(async (params: Record<string, unknown>) => {
        capturedDecision = params;
        return {
          id: "dec_1",
          kind: params.kind,
          title: params.title,
          body: params.body,
          conversationId: params.conversationId,
          scopeRef: params.scopeRef,
          status: "active",
        };
      }),
    } as unknown as MnemosyneClient;

    for (const [locale, rationale, compaction] of [
      ["en-US", /body.*rationale/i, /compaction/i],
      ["es-419", /body.*justificación/i, /compactación/i],
    ] as const) {
      const tools = await listRegisteredTools(locale);
      const decideTool = tools.get("memory_decide");
      expect(decideTool, locale).toBeDefined();
      expect(decideTool?.inputSchema?.properties?.sessionId, locale).toBeUndefined();
      expect(decideTool?.description, locale).toMatch(rationale);
      expect(decideTool?.description, locale).toMatch(/sessionId.*conversationId/);
      expect(decideTool?.description, locale).toMatch(/scopeRef/);
      expect(decideTool?.description?.length ?? 0, locale).toBeLessThanOrEqual(250);
      expect(fieldDescription(decideTool, "conversationId"), locale).toMatch(/sessionId/);

      const episodeEndTool = tools.get("memory_episode_end");
      expect(episodeEndTool, locale).toBeDefined();
      expect(episodeEndTool?.description, locale).toMatch(/pure MCP/i);
      expect(episodeEndTool?.description, locale).toMatch(/plugin/i);
      expect(episodeEndTool?.description, locale).toMatch(/harness/i);
      expect(episodeEndTool?.description, locale).toMatch(compaction);
      expect(episodeEndTool?.description, locale).toMatch(/skipped/i);
      expect(episodeEndTool?.description?.length ?? 0, locale).toBeLessThanOrEqual(250);
      const sessionIdDesc = fieldDescription(episodeEndTool, "sessionId");
      expect(sessionIdDesc, locale).toContain("Episode: open");
      expect(sessionIdDesc, locale).toContain("mnemo-managed-v1:");
      expect(sessionIdDesc, locale).toMatch(compaction);
    }

    const server = new McpServer({ name: "audit", version: "1.0.0" });
    registerDecide(server, fakeClient);
    registerEpisodeEnd(server, fakeClient);
    const client = new Client({ name: "test-client", version: "1.0.0" }, { capabilities: {} });
    const [cTransport, sTransport] = InMemoryTransport.createLinkedPair();
    await Promise.all([client.connect(cTransport), server.connect(sTransport)]);

    const res = await client.callTool({
      name: "memory_decide",
      arguments: {
        kind: "architecture",
        title: "Use Postgres",
        body: "Postgres chosen for durability",
        conversationId: "sess-provenance-1",
        scopeRef: "project-core",
      },
    });

    expect(res.isError).toBeFalsy();
    expect(capturedDecision?.body).toBe("Postgres chosen for durability");
    expect(capturedDecision?.conversationId).toBe("sess-provenance-1");
    expect(capturedDecision?.scopeRef).toBe("project-core");

    await Promise.all([client.close(), server.close()]);
  });

  it.each(["too_few_turns", "llm_unavailable"] as const)(
    "too_few_turns/llm_unavailable episode ends remain skipped rather than reported as extracted (%s)",
    async (skipReason) => {
      const fakeClient = {
        collapseSession: vi.fn(async () => ({
          accepted: true,
          sessionId: "sess-skip-1",
          status: "skipped",
          skipReason,
        })),
        withTimeout: () => fakeClient,
      } as unknown as MnemosyneClient;

      const server = new McpServer({ name: "audit", version: "1.0.0" });
      registerEpisodeEnd(server, fakeClient);
      const client = new Client({ name: "test-client", version: "1.0.0" }, { capabilities: {} });
      const [cTransport, sTransport] = InMemoryTransport.createLinkedPair();
      await Promise.all([client.connect(cTransport), server.connect(sTransport)]);

      const res = await client.callTool({
        name: "memory_episode_end",
        arguments: { sessionId: "sess-skip-1" },
      });

      expect(res.isError).toBe(false);
      const text = ((res.content as unknown[])[0] as { text: string }).text;
      expect(text).not.toMatch(/ended and collapsed/i);
      expect(text).toContain("did NOT extract");
      expect(text).toContain(skipReason);

      await Promise.all([client.close(), server.close()]);
    }
  );
});

